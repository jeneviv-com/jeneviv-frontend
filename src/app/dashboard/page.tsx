function downloadCsv(collections: Collection[], generatedBy: string) {
  const ts = new Date().toISOString();
  const rows = collections.flatMap((c) =>
    Array.from({ length: c.payerCount }).map((_, i) => [
      `Payer ${i + 1}`,
      `20/ENG/${String(i + 1).padStart(3, "0")}`,
      "+234XXXXXXXXXX",
      `payer${i + 1}@example.com`,
      String(Math.round(c.amountCollected / Math.max(c.payerCount, 1))),
      "0",
      String(Math.round(c.amountCollected / Math.max(c.payerCount, 1))),
      "PAID",
      ts.slice(0, 10),
      ts.slice(11, 19),
      `JNV-${c.id}-${i + 1}`,
      "Flutterwave",
      "—",
      c.name,
      `JNV-RCPT-${c.id}-${i + 1}`,
      `https://jeneviv.com/verify/${c.id}-${i + 1}`,
      ts,
      generatedBy,
    ]),
  );
  const csv = [CSV_HEADERS, ...rows]
    .map((r) => r.map((c) => `"${String(c).replace(/"/g, '""')}"`).join(","))
    .join("\n");
  const blob = new Blob([csv], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `jeneviv-collections-${ts.slice(0, 10)}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}

